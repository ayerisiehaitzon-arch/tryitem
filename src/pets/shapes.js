// 网球的缝线：单位球面上的一条闭合曲线（a + b = 1 时正好落在球面上），y 轴朝上
export function tennisSeam(n = 400) {
  const a = 0.72, b = 0.28, c = 2 * Math.sqrt(a * b);
  return Array.from({ length: n }, (_, i) => {
    const t = (2 * Math.PI * i) / n;
    return [a * Math.cos(t) + b * Math.cos(3 * t), c * Math.sin(2 * t), a * Math.sin(t) - b * Math.sin(3 * t)];
  });
}
// 球面上一点的贴图坐标（和网球几何用同一套）：u 绕 y 轴、v 从北极到南极
export const sphereUV = ([x, y, z]) => {
  const r = Math.hypot(x, y, z) || 1;
  return [(Math.atan2(z, x) / (2 * Math.PI) + 1) % 1, Math.acos(Math.max(-1, Math.min(1, y / r))) / Math.PI];
};
